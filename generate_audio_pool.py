VOICE = "zh-CN-YunxiNeural" # 沉穩自信男聲，極具演說感與說服力

async def generate_single_audio(item, idx, total):
    output_path = os.path.join(AUDIO_DIR, f"{item['id']}.mp3")
    print(f"🎙️ [{idx}/{total}] 正在生成: {item['title']} -> {item['id']}.mp3 ...")
    
    communicate = edge_tts.Communicate(item["text"], voice=VOICE, rate="-2%", pitch="+0Hz")
    await communicate.save(output_path)
    
    size_kb = os.path.getsize(output_path) / 1024
    print(f"✅ 完成 [{item['id']}.mp3] 大小: {size_kb:.1f} KB")

async def main():
    print(f"🚀 開始批次生成 20 支 60 秒認知語音檔...")
    print(f"📁 儲存路徑: {AUDIO_DIR}")
    print(f"🎙️ 使用音色: {VOICE} (微軟神經網絡沉穩演說音色)\n")
    
    total = len(ARTICLES)
    for idx, item in enumerate(ARTICLES, 1):
        await generate_single_audio(item, idx, total)
        await asyncio.sleep(0.2) # 禮貌間隔
        
    print(f"\n🎉 恭喜！全部 20 支 60 秒音訊檔已成功生成並存入 assets/audio/ 目錄！")

if __name__ == "__main__":
    asyncio.run(main())
