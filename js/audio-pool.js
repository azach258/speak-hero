/**
 * 隨機抽取一段音訊素材
 * @param {string|null} excludeId 要排除的當前音訊 ID
 * @returns {object} 隨機抽取的音訊素材物件
 */
export function getRandomAudio(excludeId = null) {
  const filtered = excludeId ? AUDIO_POOL.filter(a => a.id !== excludeId) : AUDIO_POOL;
  const index = Math.floor(Math.random() * filtered.length);
  return filtered[index] || AUDIO_POOL[0];
}

/**
 * 根據 ID 獲取音訊素材
 * @param {string} id 
 * @returns {object|undefined}
 */
export function getAudioById(id) {
  return AUDIO_POOL.find(a => a.id === id);
}

/**
 * 獲取所有分類清單
 * @returns {string[]}
 */
export function getAllAudioCategories() {
  const cats = new Set(AUDIO_POOL.map(a => a.category));
  return Array.from(cats);
}
